const TABLE = OPENINGS.map(([line, name]) => ({ moves: line.split(' '), name }));

/** Название дебюта по ходам партии (в записи SAN) или null, если не узнали. */
export function openingName(sans: string[]): string | null {
  let best: { moves: string[]; name: string } | null = null;
  for (const o of TABLE) {
    if (o.moves.length > sans.length) continue;
    if (o.moves.every((m, i) => m === sans[i]) && (!best || o.moves.length > best.moves.length)) best = o;
  }
  return best?.name ?? null;
}
