/** Звание по ауре за партию. */
export function auraRank(aura: number): string {
  if (aura >= 4000) return '🗿 Сигма';
  if (aura >= 1500) return '😎 Чил-гай';
  if (aura >= -500) return '🧍 НПС';
  if (aura >= -3000) return '🍺 Скуф';
  return '🤡 Клоун дня';
}
