export { VOICE } from './voicemap';

let last = '';
/** Набор фраз по уровню мата: soft — без мата, medium — «лайт», hard — всё 18+. */
function pool(g: RoastKey, tone: Tone): string[] {
  if (tone === 'soft') return SOFT[g] ?? [];
  if (tone === 'medium') return [...(MEDIUM[g] ?? []), ...(SOFT[g] ?? [])];
  return [...ROAST[g], ...(HARD[g] ?? [])];
}

/**
 * Случайная реплика; одна и та же подряд не повторяется.
 * На «18+» часть фраз берём из озвученных живым голосом.
 */
export function pickRoast(g: RoastKey, tone: Tone = 'hard', skip?: RegExp): string {
  const full = pool(g, tone);
  // skip — убрать фразы не к месту (в партии двух людей — про бота).
  const kept = skip ? full.filter((p) => !skip.test(p)) : full;
  const all = kept.length ? kept : full;
  const recorded = all.filter((p) => VOICE[p]);
  // Неозвученные фразы (новые, ещё без записи) в приложении скажет Pavel; в браузере — чаще берём записанные.
  const share = window.coachVoice ? 0.4 : 0.75;
  const list = recorded.length && Math.random() < share ? recorded : all.length ? all : ROAST[g];
  let p = list[Math.floor(Math.random() * list.length)];
  if (p === last && list.length > 1) p = list[(list.indexOf(p) + 1) % list.length];
  last = p;
  return p;
}
